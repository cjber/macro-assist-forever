#!/usr/bin/env python3
"""Generate Data/Commands.lua from the client's slash-command source.

The Blizzard files are only on a developer machine, never on CI, so the generator reads a small pinned
extraction in tools/data/ by default. Rebuild that snapshot from a WoW Forever UI dump with:

    python3 tools/gen_commands.py --extract \
        --blizzard-root ~/drive/proj/wow/wow-handoff/blizzard-ui \
        --global-strings-csv ~/.cache/wowmock/1.60.1.69913/GlobalStrings.csv

Then regenerate the addon data and check it in:

    python3 tools/gen_commands.py
    python3 tools/gen_commands.py --check

`--check` compares the checked-in file with a fresh generation. If the snapshot is not present (for
example on a partial CI checkout) it still validates the shape of the checked-in file instead of
silently passing.
"""

from __future__ import annotations

import argparse
import csv
import re
import sys
from collections import defaultdict
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "tools" / "data"
OUTPUT = ROOT / "Data" / "Commands.lua"

# The files below are the client's slash-command registry and its aliases. The extraction keeps only the
# lists this addon needs; the Blizzard Lua and the GlobalStrings CSV never ship or reach CI.
CHAT_FRAME = Path("Interface/AddOns/Blizzard_ChatFrameBase")
SLASH_COMMANDS = CHAT_FRAME / "Shared/SlashCommands.lua"
CHAT_TYPES = CHAT_FRAME / "Shared/ChatTypeInfoConstants.lua"
# The secure spell-list commands live beside SlashCommands.lua rather than inside its registration table.
EXTRA_SECURE = (
    ("CastRandomManager.lua", "CASTRANDOM"),
    ("CastSequenceManager.lua", "CASTSEQUENCE"),
)
CAST_LISTS = frozenset({"CASTRANDOM", "CASTSEQUENCE"})
KINDS = frozenset({"secure", "command", "chat", "emote"})
REGISTRATION = re.compile(r"CheckAdd(Secure)?SlashCommand\(\s*SLASH_COMMAND\.(\w+)\s*,\s*SLASH_COMMAND_CATEGORY\.(\w+)")
SLASH_ALIAS = re.compile(r"^SLASH_([A-Z0-9_]+?)(\d+)$")
EMOTE_ALIAS = re.compile(r"^EMOTE(\d+)_CMD(\d+)$")
INLINE_ALIAS = re.compile(r'^\s*SLASH_([A-Z0-9_]+?)(\d+)\s*=\s*"([^"]+)"', re.MULTILINE)
INLINE_COMMAND = re.compile(r'^\s*SLASH_COMMAND\.(\w+)\s*=\s*"([^"]+)"', re.MULTILINE)
CHAT_TYPE = re.compile(r'ChatTypeInfo\["([A-Z0-9_]+)"\]\s*=')

HEADER = "Generated by tools/gen_commands.py"


@dataclass
class Registration:
    """One slash-command registration, in source order."""

    key: str
    kind: str
    category: str
    description: str = ""


@dataclass
class Inputs:
    """The pinned lists the generator reads, plus the command table they belong to."""

    commands: dict[str, str] = field(default_factory=dict)
    categories: dict[str, int] = field(default_factory=dict)
    registrations: list[Registration] = field(default_factory=list)
    # `/text` aliases from GlobalStrings, keyed by SLASH_<KEY>.
    aliases: dict[str, list[tuple[int, str]]] = field(default_factory=lambda: defaultdict(list))
    # Aliases the client's Lua assigns itself (TEXELVIS), keyed the same way.
    inline_aliases: dict[str, list[tuple[int, str]]] = field(default_factory=lambda: defaultdict(list))
    same: dict[str, str] = field(default_factory=dict)
    chat_types: list[str] = field(default_factory=list)
    emotes: dict[int, list[tuple[int, str]]] = field(default_factory=lambda: defaultdict(list))


def lua_string(text: str) -> str:
    """`text` as a double-quoted Lua string literal."""
    escaped = (
        text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t")
    )
    return f'"{escaped}"'


def lua_list(values: list[str]) -> str:
    if not values:
        return "{}"
    return "{ " + ", ".join(lua_string(value) for value in values) + " }"


def one_line(text: str) -> str:
    return " ".join(text.replace("\t", " ").split())


def comment_before(text: str, offset: int) -> str:
    """The contiguous `--` comment directly above the line holding `offset`, joined to one line."""
    start = text.rfind("\n", 0, offset) + 1
    if not re.fullmatch(r"\s*(?:SlashCommandUtil\.)?", text[start:offset]):
        return ""
    pieces: list[str] = []
    cursor = start
    while cursor > 0:
        previous_end = cursor - 1
        previous_start = text.rfind("\n", 0, previous_end) + 1
        line = text[previous_start:previous_end].strip()
        if not line.startswith("--") or line.startswith("--[["):
            break
        pieces.append(one_line(line[2:]))
        cursor = previous_start
    return one_line(" ".join(reversed(pieces)))


def extract_registrations(text: str) -> list[Registration]:
    registrations = []
    for match in REGISTRATION.finditer(text):
        registrations.append(
            Registration(
                key=match.group(2),
                kind="secure" if match.group(1) else "command",
                category=match.group(3),
                description=comment_before(text, match.start()),
            )
        )
    return registrations


def extract_inputs(blizzard_root: Path, global_strings: Path) -> Inputs:
    """Read the raw Blizzard source and CSV into the pinned lists."""
    inputs = Inputs()
    slash_text = (blizzard_root / SLASH_COMMANDS).read_text(encoding="utf-8")
    inputs.commands = dict(
        re.findall(r'^[ \t]*([A-Z0-9_]+)\s*=\s*"([^"]+)"', slash_text.split("SLASH_COMMAND_CATEGORY")[0], re.MULTILINE)
    )
    category_block = slash_text.split("SLASH_COMMAND_CATEGORY", 1)[1].split("COMMANDS_BY_GAME_MODE", 1)[0]
    inputs.categories = {name: int(value) for name, value in re.findall(r"([A-Z0-9_]+)\s*=\s*(\d+)", category_block)}
    # The helpers are called from a few addons, not only ChatFrameBase: grep the whole AddOns tree.
    inputs.registrations = []
    for path in sorted((blizzard_root / "Interface/AddOns").rglob("*.lua")):
        text = path.read_text(encoding="utf-8", errors="replace")
        if "CheckAdd" in text:
            inputs.registrations.extend(extract_registrations(text))

    # Castsequence and castrandom are registered in their own managers, not in SlashCommands.lua.
    for filename, key in EXTRA_SECURE:
        manager = (blizzard_root / CHAT_FRAME / "Shared" / filename).read_text(encoding="utf-8")
        match = re.search(rf'SecureCmdList\[\s*"{key}"\s*\]\s*=\s*function', manager)
        if match is None:
            continue
        inputs.registrations.append(Registration(key, "secure", "COMBAT", comment_before(manager, match.start())))
        if key == "CASTRANDOM":
            # USERANDOM is the same callback under another name; its aliases belong on the castrandom entry.
            for alias_key, target in re.findall(
                r'SecureCmdList\[\s*"([A-Z0-9_]+)"\s*\]\s*=\s*SecureCmdList\[\s*"([A-Z0-9_]+)"\s*\]', manager
            ):
                inputs.same[alias_key] = target

    # The client can also assign a command key and aliases inline (TEXELVIS inside IsGMClient()).
    for key, value in INLINE_COMMAND.findall(slash_text):
        inputs.commands.setdefault(key, value)
    for key, index, value in INLINE_ALIAS.findall(slash_text):
        if value.startswith("/"):
            inputs.inline_aliases[key].append((int(index), value[1:].lower()))

    chat_text = (blizzard_root / CHAT_TYPES).read_text(encoding="utf-8")
    inputs.chat_types = sorted(set(CHAT_TYPE.findall(chat_text)))

    with global_strings.open(newline="", encoding="utf-8") as handle:
        for row in csv.DictReader(handle):
            tag = row["BaseTag"]
            value = row["TagText_lang"].strip()
            if not value.startswith("/"):
                continue
            slash = SLASH_ALIAS.match(tag)
            if slash:
                inputs.aliases[slash.group(1)].append((int(slash.group(2)), value[1:].lower()))
            else:
                emote = EMOTE_ALIAS.match(tag)
                if emote:
                    inputs.emotes[int(emote.group(1))].append((int(emote.group(2)), value[1:].lower()))
    for key, values in inputs.aliases.items():
        inputs.aliases[key] = sorted(set(values))
    for key, values in inputs.inline_aliases.items():
        inputs.inline_aliases[key] = sorted(set(values))
    for key, values in inputs.emotes.items():
        inputs.emotes[key] = sorted(set(values))
    return inputs


def read_commands(path: Path, inputs: Inputs) -> None:
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        fields = line.split("\t")
        tag = fields[0]
        if tag == "command" and len(fields) >= 2:
            key, _, value = fields[1].partition("=")
            inputs.commands[key] = value
        elif tag == "category" and len(fields) >= 2:
            name, _, value = fields[1].partition("=")
            inputs.categories[name] = int(value)
        elif tag == "register" and len(fields) >= 4:
            inputs.registrations.append(
                Registration(fields[2], fields[1], fields[3], one_line(fields[4]) if len(fields) > 4 else "")
            )
        elif tag == "alias" and len(fields) >= 4:
            value = fields[3]
            if value.startswith("/"):
                inputs.inline_aliases[fields[1]].append((int(fields[2]), value[1:].lower()))
        elif tag == "same" and len(fields) >= 3:
            inputs.same[fields[1]] = fields[2]
    for key, values in inputs.aliases.items():
        inputs.aliases[key] = sorted(set(values))
    for key, values in inputs.inline_aliases.items():
        inputs.inline_aliases[key] = sorted(set(values))


def read_chat_types(path: Path) -> list[str]:
    types = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if line and not line.startswith("#"):
            types.append(line)
    return types


def read_global_strings(path: Path, inputs: Inputs) -> None:
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        fields = line.split("\t")
        if len(fields) < 4 or not fields[3].startswith("/"):
            continue
        value = fields[3][1:].lower()
        if fields[0] == "slash":
            inputs.aliases[fields[1]].append((int(fields[2]), value))
        elif fields[0] == "emote":
            inputs.emotes[int(fields[1])].append((int(fields[2]), value))
    for key, values in inputs.aliases.items():
        inputs.aliases[key] = sorted(set(values))
    for key, values in inputs.emotes.items():
        inputs.emotes[key] = sorted(set(values))


def write_snapshot(data_dir: Path, inputs: Inputs) -> None:
    data_dir.mkdir(parents=True, exist_ok=True)
    command_lines = [
        "# Pinned slash-command input for tools/gen_commands.py. Regenerate with its --extract mode.",
        "# command KEY=VALUE     SLASH_COMMAND's key and its SLASH_<VALUE> alias prefix",
        "# category NAME=NUMBER  SLASH_COMMAND_CATEGORY",
        "# register KIND KEY CATEGORY [description]",
        "# alias KEY NUMBER /text  an alias assigned in Lua rather than GlobalStrings",
        "# same KEY TARGET          a second SecureCmdList name for the same callback",
    ]
    command_lines += [f"command\t{key}={inputs.commands[key]}" for key in sorted(inputs.commands)]
    command_lines += [f"category\t{name}={inputs.categories[name]}" for name in sorted(inputs.categories)]
    for registration in sorted(inputs.registrations, key=lambda item: (item.key, item.kind)):
        fields = ["register", registration.kind, registration.key, registration.category]
        if registration.description:
            fields.append(one_line(registration.description))
        command_lines.append("\t".join(fields))
    for key, values in sorted(inputs.inline_aliases.items()):
        for index, value in values:
            command_lines.append(f"alias\t{key}\t{index}\t/{value}")
    for key, target in sorted(inputs.same.items()):
        command_lines.append(f"same\t{key}\t{target}")
    (data_dir / "commands.txt").write_text("\n".join(command_lines) + "\n", encoding="utf-8")

    chat_lines = [
        "# Pinned ChatTypeInfo keys for tools/gen_commands.py. Regenerate with its --extract mode.",
        *inputs.chat_types,
    ]
    (data_dir / "chat_types.txt").write_text("\n".join(chat_lines) + "\n", encoding="utf-8")

    global_lines = [
        "# Pinned /text aliases for tools/gen_commands.py. Regenerate with its --extract mode.",
        "# slash KEY NUMBER /text   from SLASH_<KEY><NUMBER> in GlobalStrings.csv",
        "# emote ID NUMBER /text    from EMOTE<ID>_CMD<NUMBER> in GlobalStrings.csv",
    ]
    for key, values in sorted(inputs.aliases.items()):
        for index, value in values:
            global_lines.append(f"slash\t{key}\t{index}\t/{value}")
    for key, values in sorted(inputs.emotes.items()):
        for index, value in values:
            global_lines.append(f"emote\t{key}\t{index}\t/{value}")
    (data_dir / "global_strings.txt").write_text("\n".join(global_lines) + "\n", encoding="utf-8")


def alias_pool(inputs: Inputs, key: str) -> dict[str, int]:
    """Alias text (without slash) to its lowest index, with Lua aliases and `same` names folded in."""
    pool: dict[str, int] = {}
    for name in (key,):
        for index, value in inputs.aliases.get(name, []):
            pool[value] = min(pool.get(value, index), index)
        for index, value in inputs.inline_aliases.get(name, []):
            pool[value] = min(pool.get(value, index), index)
    for alias_key, target in inputs.same.items():
        if target == key or alias_key == key:
            for index, value in inputs.aliases.get(alias_key, []):
                pool[value] = min(pool.get(value, index), index)
            for index, value in inputs.inline_aliases.get(alias_key, []):
                pool[value] = min(pool.get(value, index), index)
    return pool


def canonical(pool: dict[str, int], preferred: str) -> str | None:
    """The alias text (without slash) to call the command, preferring the command's own name."""
    if preferred in pool:
        return preferred
    if not pool:
        return None
    return min(pool, key=lambda value: (pool[value], value))


def build_entries(inputs: Inputs) -> list[dict]:
    candidates: list[dict] = []

    for registration in sorted(inputs.registrations, key=lambda item: item.key):
        value = inputs.commands.get(registration.key, registration.key)
        pool = alias_pool(inputs, value)
        if not pool and value != registration.key:
            pool = alias_pool(inputs, registration.key)
        name = canonical(pool, registration.key.lower())
        aliases = []
        if name:
            aliases = [name]
            aliases += sorted(alias for alias in pool if alias != name)
        else:
            name = registration.key.lower()
        conditions = registration.kind == "secure"
        entry = {
            "name": name,
            "aliases": aliases,
            "kind": registration.kind,
            "category": registration.category,
            "conditions": conditions,
        }
        if registration.key in CAST_LISTS or entry["name"] in {"castsequence", "castrandom"}:
            entry["list"] = True
        if registration.description:
            entry["description"] = one_line(registration.description)
        candidates.append(entry)

    for key in inputs.chat_types:
        pool = alias_pool(inputs, key)
        name = canonical(pool, key.lower())
        if name is None:
            # A chat type with no /text alias cannot be typed; only the keys that are commands belong here.
            continue
        aliases = [name] + sorted(alias for alias in pool if alias != name)
        candidates.append(
            {
                "name": name,
                "aliases": aliases,
                "kind": "chat",
                "category": "CHAT",
                "conditions": False,
            }
        )

    for emote in sorted(inputs.emotes):
        pool = {value: index for index, value in inputs.emotes[emote]}
        name = canonical(pool, "")
        if name is None:
            continue
        aliases = [name] + sorted(alias for alias in pool if alias != name)
        candidates.append(
            {
                "name": name,
                "aliases": aliases,
                "kind": "emote",
                "category": "EMOTE",
                "conditions": False,
            }
        )

    # One owner per alias: commands first, then chat types, then emotes. This keeps the table deterministic and
    # stops a chat alias such as /r from appearing twice.
    precedence = {"secure": 0, "command": 0, "chat": 1, "emote": 2}
    candidates.sort(key=lambda item: (precedence[item["kind"]], item["name"], item["kind"]))
    used: set[str] = set()
    entries: list[dict] = []
    for entry in candidates:
        if not entry["aliases"]:
            # A registered command the client gave no /text alias: keep it for the record, but it cannot be typed.
            entries.append(entry)
            continue
        free = [alias for alias in entry["aliases"] if alias not in used]
        if not free:
            continue
        if entry["name"] not in free:
            entry["name"] = free[0]
        entry["aliases"] = [entry["name"]] + sorted(alias for alias in free if alias != entry["name"])
        used.update(entry["aliases"])
        entries.append(entry)
    entries.sort(key=lambda item: (item["name"], item["kind"]))
    return entries


def render(entries: list[dict]) -> str:
    lines = [
        "local _, ns = ...",
        "",
        "if ns.broken then",
        "\treturn",
        "end",
        "",
        f"-- {HEADER} from the client's slash-command registrations and ChatTypeInfoConstants.lua.",
        "-- Do not edit by hand: change the generator or the pinned lists in tools/data, then regenerate.",
        "",
        "---A slash command the client knows.",
        "---@class MacroAssistCommand",
        "---@field name string the canonical text without the leading slash",
        "---@field aliases string[] every usable text without the slash, canonical first",
        '---@field kind "secure"|"command"|"chat"|"emote"',
        "---@field category string the client's slash-command category, or CHAT/EMOTE",
        "---@field conditions boolean whether the command reads macro conditions",
        "---@field list boolean? true when the argument is a comma-separated spell list",
        "---@field description string? a description quoted from the client source",
        "",
        "---@type MacroAssistCommand[]",
        "ns.Commands = {",
    ]
    for entry in entries:
        lines.append("\t{")
        lines.append(f"\t\tname = {lua_string(entry['name'])},")
        lines.append(f"\t\taliases = {lua_list(entry['aliases'])},")
        lines.append(f"\t\tkind = {lua_string(entry['kind'])},")
        lines.append(f"\t\tcategory = {lua_string(entry['category'])},")
        lines.append(f"\t\tconditions = {'true' if entry['conditions'] else 'false'},")
        if entry.get("list"):
            lines.append("\t\tlist = true,")
        if entry.get("description"):
            lines.append(f"\t\tdescription = {lua_string(entry['description'])},")
        lines.append("\t},")
    lines += [
        "}",
        "",
        "-- Lower-case alias without the slash to its entry; the first owner wins.",
        "---@type table<string, MacroAssistCommand>",
        "ns.CommandAliases = {}",
        "for _, command in ipairs(ns.Commands) do",
        "\tfor _, alias in ipairs(command.aliases) do",
        "\t\tif ns.CommandAliases[alias] == nil then",
        "\t\t\tns.CommandAliases[alias] = command",
        "\t\tend",
        "\tend",
        "\tif ns.CommandAliases[command.name] == nil then",
        "\t\tns.CommandAliases[command.name] = command",
        "\tend",
        "end",
        "",
    ]
    return "\n".join(lines)


def validate_shape(text: str) -> list[str]:
    """Every structural problem with a checked-in Data/Commands.lua, without executing it."""
    problems: list[str] = []
    if HEADER not in text:
        problems.append(f"missing the '{HEADER}' header")
    if "ns.CommandAliases = {}" not in text:
        problems.append("missing ns.CommandAliases")
    start = text.find("ns.Commands = {")
    if start == -1:
        problems.append("missing ns.Commands")
        return problems
    body = text[start + len("ns.Commands = {") :]
    end = body.find("\n}\n")
    if end == -1:
        problems.append("ns.Commands has no closing brace")
        return problems
    entries = 0
    current: dict[str, str] = {}

    def finish(number: int) -> None:
        if not current:
            problems.append(f"entry {number} has no fields")
            return
        name = current.get("name", "")
        kind = current.get("kind", "").strip('"')
        conditions = current.get("conditions")
        if not re.fullmatch(r'"[^"]+"', name):
            problems.append(f"entry {number}: name is not a non-empty string")
        if kind not in KINDS:
            problems.append(f"entry {number}: unknown kind {kind!r}")
        if not current.get("category", '""').strip('"'):
            problems.append(f"entry {number}: empty category")
        if conditions not in {"true", "false"}:
            problems.append(f"entry {number}: conditions is not a boolean")
        aliases = current.get("aliases")
        if aliases is None or not aliases.startswith("{") or not aliases.endswith("}"):
            problems.append(f"entry {number}: aliases is not a table")
        elif name:
            first = re.search(r'"([^"]*)"', aliases)
            if first and first.group(1) != name.strip('"'):
                problems.append(f"entry {number}: the canonical alias is not first")
        if conditions == "true" and kind not in {"secure"}:
            problems.append(f"entry {number}: {kind} commands cannot take conditions")
        if kind == "secure" and conditions == "false":
            problems.append(f"entry {number}: a secure command must take conditions")

    for number, raw in enumerate(body[:end].splitlines(), 1):
        line = raw.strip()
        if not line:
            continue
        if line == "{":
            entries += 1
            current = {}
            continue
        if line in {"},", "}"}:
            if entries and current:
                finish(entries)
            continue
        field = re.match(r"^(\w+) = (.+)$", line.rstrip(","))
        if field is None:
            problems.append(f"entry {entries + 1}, body line {number}: not a field: {line}")
            continue
        key, value = field.group(1), field.group(2)
        if key not in {"name", "aliases", "kind", "category", "conditions", "list", "description"}:
            problems.append(f"entry {entries + 1}: unknown field {key}")
        else:
            current[key] = value
    if entries == 0:
        problems.append("ns.Commands is empty")
    return problems


def load_inputs(commands: Path, chat_types: Path, global_strings: Path) -> Inputs | None:
    if not (commands.is_file() and chat_types.is_file() and global_strings.is_file()):
        return None
    inputs = Inputs()
    read_commands(commands, inputs)
    inputs.chat_types = read_chat_types(chat_types)
    read_global_strings(global_strings, inputs)
    return inputs


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--commands", type=Path, default=DATA / "commands.txt", help="pinned command extraction")
    parser.add_argument("--chat-types", type=Path, default=DATA / "chat_types.txt", help="pinned ChatTypeInfo keys")
    parser.add_argument("--global-strings", type=Path, default=DATA / "global_strings.txt", help="pinned /text aliases")
    parser.add_argument("--output", type=Path, default=OUTPUT, help="the generated Lua file")
    parser.add_argument("--check", action="store_true", help="exit 1 when the checked-in file is stale or malformed")
    parser.add_argument("--extract", action="store_true", help="rebuild the pinned lists from a client dump")
    parser.add_argument("--blizzard-root", type=Path, help="the client's Interface parent (with --extract)")
    parser.add_argument("--global-strings-csv", type=Path, help="the client's GlobalStrings.csv (with --extract)")
    parser.add_argument("--data-dir", type=Path, default=DATA, help="where --extract writes the pinned lists")
    args = parser.parse_args(argv)

    if args.extract:
        if args.blizzard_root is None or args.global_strings_csv is None:
            parser.error("--extract needs --blizzard-root and --global-strings-csv")
        write_snapshot(args.data_dir, extract_inputs(args.blizzard_root, args.global_strings_csv))
        print(f"Wrote the pinned command input to {args.data_dir}")
        return 0

    inputs = load_inputs(args.commands, args.chat_types, args.global_strings)
    checked_in = args.output.read_text(encoding="utf-8") if args.output.is_file() else None

    if args.check:
        if checked_in is None:
            print(f"{args.output}: missing", file=sys.stderr)
            return 1
        problems = validate_shape(checked_in)
        if problems:
            for problem in problems:
                print(f"{args.output}: {problem}", file=sys.stderr)
            return 1

    if inputs is None:
        if args.check:
            print(f"{args.output}: shape is valid; the pinned input is unavailable, so it was not regenerated")
            return 0
        print("The pinned input in tools/data is missing; run --extract first.", file=sys.stderr)
        return 1

    expected = render(build_entries(inputs))
    if args.check:
        if checked_in != expected:
            print(
                f"{args.output}: stale; run python3 tools/gen_commands.py and check the result in",
                file=sys.stderr,
            )
            return 1
        print(f"{args.output}: {checked_in.count('name = ')} entries match the pinned input")
        return 0

    args.output.parent.mkdir(parents=True, exist_ok=True)
    if checked_in != expected:
        args.output.write_text(expected, encoding="utf-8")
        print(f"Wrote {args.output}")
    else:
        print(f"{args.output} is already up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
