#!/usr/bin/env python3
"""Generate Data/IconNames.lua from the client's icon file names.

The client's icon provider hands the picker FileDataIDs, so a search over file names, a tooltip
and the class/school/slot filters need an ID-to-name table. The names only exist in the client's
listfile, which is never on CI, so the generator reads a pinned extraction in tools/data/ by
default. Rebuild that snapshot from wago.tools with:

    python3 tools/gen_icon_names.py --extract

Then regenerate the addon data and check it in:

    python3 tools/gen_icon_names.py
    python3 tools/gen_icon_names.py --check

`--check` compares the checked-in file with a fresh generation. If the snapshot is not present
(for example on a partial CI checkout) it still validates the shape of the checked-in file instead
of silently passing.

The addon keeps the table as one long-string literal and parses it on the first lookup, so opening
the picker, not logging in, pays for it.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

from forever_tools import wago

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "tools" / "data"
OUTPUT = ROOT / "Data" / "IconNames.lua"
CACHE = ROOT / "tools" / ".cache" / "icon-names"

# The data pin every other client table in this repo shares (tools/forever_sim/fetch.py).
BUILD = "1.60.1.70425"
URL = f"https://wago.tools/api/files?search=interface%2Ficons%2F&version={BUILD}&build={BUILD}"
USER_AGENT = "MacroAssistForever/1.0 (+https://github.com/cjber/macro-assist-forever)"

HEADER = "Generated by tools/gen_icon_names.py"
ENTRY = re.compile(r"^(\d+)=(.+)$")


def normalise(path: str) -> str | None:
    """One listfile path as `FileDataID=name`, or None when it is not a loose icon."""
    path = path.replace("\\", "/").lower()
    if not path.startswith("interface/icons/") or not path.endswith(".blp"):
        return None
    return path[len("interface/icons/") : -len(".blp")].strip()


def extract(rows: dict[str, str]) -> list[tuple[int, str]]:
    """The `interface/icons/` entries in FileDataID order, without a suffix."""
    icons: list[tuple[int, str]] = []
    for raw_id, path in rows.items():
        name = normalise(path)
        if name is None:
            continue
        try:
            file_id = int(raw_id)
        except ValueError:
            continue
        if file_id > 0:
            icons.append((file_id, name))
    icons.sort()
    return icons


def validate(data: bytes) -> None:
    """Reject an HTML error page or an implausibly small icon slice before it is cached."""
    try:
        rows = json.loads(data)
    except json.JSONDecodeError as error:
        raise ValueError(f"wago.tools returned non-JSON listfile data: {error}") from error
    if not isinstance(rows, dict) or len(rows) < 1000:
        raise ValueError("wago.tools returned an empty or implausibly small listfile")


def read_snapshot(path: Path) -> list[tuple[int, str]] | None:
    if not path.is_file():
        return None
    icons: list[tuple[int, str]] = []
    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if not line or line.startswith("#"):
            continue
        match = ENTRY.match(line)
        if match is None:
            raise ValueError(f"{path}:{number}: expected FileDataID=name")
        icons.append((int(match[1]), match[2]))
    return icons


def write_snapshot(path: Path, icons: list[tuple[int, str]]) -> None:
    lines = [
        f"# interface/icons/ paths from client build {BUILD}, as FileDataID=name.",
        "# Generated by tools/gen_icon_names.py --extract. Do not edit by hand.",
        *(f"{file_id}={name}" for file_id, name in icons),
    ]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def render(icons: list[tuple[int, str]]) -> str:
    """The Lua data file: one long-string literal, parsed lazily by Core/Icons.lua."""
    if any("]]" in name for _, name in icons):
        raise ValueError("an icon name contains ']]' and cannot live in a long string")
    body = "\n".join(f"{file_id}={name}" for file_id, name in icons)
    return (
        "local _, ns = ...\n"
        "\n"
        "if ns.broken then\n"
        "\treturn\n"
        "end\n"
        "\n"
        f"-- {HEADER} from the wago.tools listfile at build {BUILD}.\n"
        f"-- {len(icons)} interface/icons/ file names, keyed by FileDataID. Do not edit by hand:\n"
        "-- change the generator or the pinned extraction in tools/data, then regenerate.\n"
        "\n"
        "-- One string, so login reads one constant and the first icon lookup parses it.\n"
        "ns.IconNameText = [==[\n"
        f"{body}\n"
        "]==]\n"
    )


def validate_shape(text: str) -> list[str]:
    """Check the checked-in file without the snapshot, for a partial checkout."""
    problems: list[str] = []
    if "ns.IconNameText = [==[" not in text:
        problems.append("ns.IconNameText is not a long string")
    body = text.split("[==[", 1)[1].rsplit("]==]", 1)[0] if "[==[" in text and "]==]" in text else ""
    entries = 0
    for line in body.splitlines():
        if not line:
            continue
        if ENTRY.match(line) is None:
            problems.append(f"entry {entries + 1}: not FileDataID=name: {line[:60]}")
            break
        entries += 1
    if entries < 1000:
        problems.append(f"only {entries} icon names")
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--snapshot", type=Path, default=DATA / "icon_names.txt", help="pinned icon extraction")
    parser.add_argument("--output", type=Path, default=OUTPUT, help="the generated Lua file")
    parser.add_argument("--check", action="store_true", help="exit 1 when the checked-in file is stale or malformed")
    parser.add_argument("--extract", action="store_true", help="rebuild the pinned extraction from wago.tools")
    parser.add_argument("--refresh", action="store_true", help="download the listfile again with --extract")
    args = parser.parse_args(argv)

    if args.extract:
        data = wago.fetch(
            URL,
            CACHE / f"listfile-{BUILD}.json",
            user_agent=USER_AGENT,
            refresh=args.refresh,
            timeout=900,
            validate=validate,
        )
        icons = extract(json.loads(data))
        if not icons:
            print("wago.tools returned no interface/icons/ paths", file=sys.stderr)
            return 1
        write_snapshot(args.snapshot, icons)
        print(f"Wrote {len(icons)} icon names to {args.snapshot}")
        return 0

    checked_in = args.output.read_text(encoding="utf-8") if args.output.is_file() else None
    if args.check:
        if checked_in is None:
            print(f"{args.output}: missing", file=sys.stderr)
            return 1
        problems = validate_shape(checked_in)
        if problems:
            for problem in problems:
                print(f"{args.output}: {problem}", file=sys.stderr)
            return 1

    icons = read_snapshot(args.snapshot)
    if icons is None:
        if args.check:
            print(f"{args.output}: shape is valid; the pinned extraction is unavailable, so it was not regenerated")
            return 0
        print(f"The pinned extraction {args.snapshot} is missing; run --extract first.", file=sys.stderr)
        return 1

    expected = render(icons)
    if args.check:
        if checked_in != expected:
            print(
                f"{args.output}: stale; run python3 tools/gen_icon_names.py and check the result in",
                file=sys.stderr,
            )
            return 1
        print(f"{args.output}: {len(icons)} icon names match the pinned extraction")
        return 0

    args.output.parent.mkdir(parents=True, exist_ok=True)
    if checked_in != expected:
        args.output.write_text(expected, encoding="utf-8")
        print(f"Wrote {args.output}")
    else:
        print(f"{args.output} is already up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
